def _art(s: str) -> list:
    return s.strip("\n").splitlines()


PORTRAITS = {
    "vera": {
        "neutral": _art(_VERA_NEUTRAL),
        "happy": _art(_VERA_HAPPY),
        "angry": _art(_VERA_ANGRY),
    },
    "rex": {
        "neutral": _art(_REX_NEUTRAL),
        "happy": _art(_REX_HAPPY),
        "angry": _art(_REX_ANGRY),
    },
    "alien": {
        "neutral": _art(_ALIEN_)
    }
}


def get_portrait(char_id: str, mood: str = "neutral") -> list:
    moods = PORTRAITS.get(char_id)
    if not moods:
        return []
    return moods.get(mood) or moods.get("neutral", [])
